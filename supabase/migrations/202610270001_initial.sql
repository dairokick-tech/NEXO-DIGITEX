-- NOVA DIGITEX: esquema inicial para Supabase Free (multiempresa en una sola base).
-- Ejecutar desde Supabase SQL Editor o mediante Supabase CLI.
begin;

create extension if not exists pgcrypto;

create table if not exists public.companies (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(trim(name)) between 2 and 180),
  tax_id text,
  business_type text not null default 'general'
    check (business_type in ('general','minimarket','clothing','hardware','pharmacy','restaurant','bookstore','electronics','wholesale','agriculture','lodging')),
  slug text not null unique,
  currency char(3) not null default 'PEN',
  created_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  active boolean not null default true
);
create unique index if not exists companies_tax_id_unique
  on public.companies (tax_id) where tax_id is not null and trim(tax_id) <> '';

create table if not exists public.company_members (
  company_id uuid not null references public.companies(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null default 'cashier' check (role in ('owner','admin','manager','cashier','inventory')),
  created_at timestamptz not null default now(),
  primary key (company_id, user_id)
);

create or replace function public.is_company_member(_company_id uuid)
returns boolean language sql stable security definer
set search_path = public
as $$
  select exists (
    select 1 from public.company_members m
    where m.company_id = _company_id and m.user_id = auth.uid()
  );
$$;

create or replace function public.has_company_role(_company_id uuid, _roles text[])
returns boolean language sql stable security definer
set search_path = public
as $$
  select exists (
    select 1 from public.company_members m
    where m.company_id = _company_id and m.user_id = auth.uid() and m.role = any(_roles)
  );
$$;

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies(id) on delete cascade,
  sku text,
  barcode text,
  name text not null check (char_length(trim(name)) between 1 and 180),
  category text,
  unit text not null default 'unidad',
  cost numeric(12,2) not null default 0 check (cost >= 0),
  price numeric(12,2) not null default 0 check (price >= 0),
  stock numeric(14,3) not null default 0,
  min_stock numeric(14,3) not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (company_id, sku)
);
create index if not exists products_company_name_idx on public.products(company_id, name);

create table if not exists public.customers (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies(id) on delete cascade,
  document_type text,
  document_number text,
  name text not null,
  phone text,
  email text,
  address text,
  created_at timestamptz not null default now()
);
create index if not exists customers_company_name_idx on public.customers(company_id, name);

create table if not exists public.suppliers (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies(id) on delete cascade,
  tax_id text,
  name text not null,
  phone text,
  email text,
  address text,
  created_at timestamptz not null default now()
);

create table if not exists public.cash_sessions (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies(id) on delete cascade,
  opened_by uuid not null references auth.users(id),
  opened_at timestamptz not null default now(),
  opening_amount numeric(12,2) not null default 0 check (opening_amount >= 0),
  closed_by uuid references auth.users(id),
  closed_at timestamptz,
  closing_amount numeric(12,2),
  status text not null default 'open' check (status in ('open','closed')),
  notes text
);

create table if not exists public.sales (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies(id) on delete cascade,
  sale_number bigint generated by default as identity,
  customer_id uuid references public.customers(id) on delete set null,
  cash_session_id uuid references public.cash_sessions(id) on delete set null,
  cashier_id uuid not null references auth.users(id),
  status text not null default 'completed' check (status in ('draft','completed','cancelled','refunded')),
  payment_method text not null default 'cash' check (payment_method in ('cash','card','transfer','wallet','credit','mixed')),
  subtotal numeric(12,2) not null default 0 check (subtotal >= 0),
  discount numeric(12,2) not null default 0 check (discount >= 0),
  tax numeric(12,2) not null default 0 check (tax >= 0),
  total numeric(12,2) not null default 0 check (total >= 0),
  created_at timestamptz not null default now(),
  unique (company_id, sale_number)
);
create index if not exists sales_company_date_idx on public.sales(company_id, created_at desc);

create table if not exists public.sale_items (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies(id) on delete cascade,
  sale_id uuid not null references public.sales(id) on delete cascade,
  product_id uuid references public.products(id) on delete set null,
  description text not null,
  quantity numeric(14,3) not null check (quantity > 0),
  unit_price numeric(12,2) not null check (unit_price >= 0),
  discount numeric(12,2) not null default 0 check (discount >= 0),
  line_total numeric(12,2) not null check (line_total >= 0),
  created_at timestamptz not null default now()
);
create index if not exists sale_items_company_sale_idx on public.sale_items(company_id, sale_id);

create table if not exists public.inventory_movements (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies(id) on delete cascade,
  product_id uuid not null references public.products(id) on delete restrict,
  movement_type text not null check (movement_type in ('in','out','adjustment','sale','return')),
  quantity numeric(14,3) not null,
  reference text,
  created_by uuid not null references auth.users(id),
  created_at timestamptz not null default now()
);
create index if not exists inventory_movements_company_date_idx on public.inventory_movements(company_id, created_at desc);

create table if not exists public.audit_log (
  id bigint generated always as identity primary key,
  company_id uuid not null references public.companies(id) on delete cascade,
  actor_id uuid references auth.users(id) on delete set null,
  action text not null,
  entity_type text not null,
  entity_id text,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

-- Crear empresa y asignar automáticamente al usuario actual como propietario.
create or replace function public.create_company(_name text, _tax_id text default null, _business_type text default 'general')
returns uuid language plpgsql security definer
set search_path = public
as $$
declare
  v_id uuid;
  v_slug text;
begin
  if auth.uid() is null then raise exception 'Debes iniciar sesión.'; end if;
  if char_length(trim(coalesce(_name,''))) < 2 then raise exception 'Nombre de empresa no válido.'; end if;
  if _business_type not in ('general','minimarket','clothing','hardware','pharmacy','restaurant','bookstore','electronics','wholesale','agriculture','lodging') then
    raise exception 'Rubro no válido.';
  end if;
  v_id := gen_random_uuid();
  v_slug := trim(both '-' from regexp_replace(lower(trim(_name)), '[^a-z0-9]+', '-', 'g'));
  v_slug := left(coalesce(nullif(v_slug,''),'empresa'), 38) || '-' || left(replace(v_id::text,'-',''), 8);
  insert into public.companies(id,name,tax_id,business_type,slug,created_by)
    values(v_id,trim(_name),nullif(trim(coalesce(_tax_id,'')),''),_business_type,v_slug,auth.uid());
  insert into public.company_members(company_id,user_id,role) values(v_id,auth.uid(),'owner');
  insert into public.audit_log(company_id,actor_id,action,entity_type,entity_id)
    values(v_id,auth.uid(),'company.created','company',v_id::text);
  return v_id;
end;
$$;

alter table public.companies enable row level security;
alter table public.company_members enable row level security;
alter table public.products enable row level security;
alter table public.customers enable row level security;
alter table public.suppliers enable row level security;
alter table public.cash_sessions enable row level security;
alter table public.sales enable row level security;
alter table public.sale_items enable row level security;
alter table public.inventory_movements enable row level security;
alter table public.audit_log enable row level security;

drop policy if exists companies_read_members on public.companies;
create policy companies_read_members on public.companies for select to authenticated
  using (public.is_company_member(id));
drop policy if exists members_read_same_company on public.company_members;
create policy members_read_same_company on public.company_members for select to authenticated
  using (public.is_company_member(company_id));
drop policy if exists products_company_access on public.products;
create policy products_company_access on public.products for all to authenticated
  using (public.is_company_member(company_id))
  with check (public.has_company_role(company_id, array['owner','admin','manager','inventory','cashier']));
drop policy if exists customers_company_access on public.customers;
create policy customers_company_access on public.customers for all to authenticated
  using (public.is_company_member(company_id))
  with check (public.has_company_role(company_id, array['owner','admin','manager','cashier']));
drop policy if exists suppliers_company_access on public.suppliers;
create policy suppliers_company_access on public.suppliers for all to authenticated
  using (public.is_company_member(company_id))
  with check (public.has_company_role(company_id, array['owner','admin','manager','inventory']));
drop policy if exists cash_sessions_company_access on public.cash_sessions;
create policy cash_sessions_company_access on public.cash_sessions for all to authenticated
  using (public.is_company_member(company_id))
  with check (public.has_company_role(company_id, array['owner','admin','manager','cashier']));
drop policy if exists sales_company_access on public.sales;
create policy sales_company_access on public.sales for all to authenticated
  using (public.is_company_member(company_id))
  with check (public.has_company_role(company_id, array['owner','admin','manager','cashier']));
drop policy if exists sale_items_company_access on public.sale_items;
create policy sale_items_company_access on public.sale_items for all to authenticated
  using (public.is_company_member(company_id))
  with check (public.is_company_member(company_id) and exists (
    select 1 from public.sales s where s.id = sale_id and s.company_id = company_id
  ));
drop policy if exists inventory_company_access on public.inventory_movements;
create policy inventory_company_access on public.inventory_movements for all to authenticated
  using (public.is_company_member(company_id))
  with check (public.has_company_role(company_id, array['owner','admin','manager','inventory']));
drop policy if exists audit_company_read on public.audit_log;
create policy audit_company_read on public.audit_log for select to authenticated
  using (public.is_company_member(company_id));
drop policy if exists audit_company_insert on public.audit_log;
create policy audit_company_insert on public.audit_log for insert to authenticated
  with check (public.is_company_member(company_id) and actor_id = auth.uid());

revoke all on function public.is_company_member(uuid) from public;
revoke all on function public.has_company_role(uuid,text[]) from public;
grant execute on function public.is_company_member(uuid) to authenticated;
grant execute on function public.has_company_role(uuid,text[]) to authenticated;
revoke all on function public.create_company(text,text,text) from public;
grant execute on function public.create_company(text,text,text) to authenticated;

grant select on public.companies, public.company_members to authenticated;
grant select, insert, update, delete on public.products, public.customers, public.suppliers,
  public.cash_sessions, public.sales, public.sale_items, public.inventory_movements to authenticated;
grant select, insert on public.audit_log to authenticated;
grant usage, select on all sequences in schema public to authenticated;

commit;
